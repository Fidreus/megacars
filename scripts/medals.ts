// Regenerates src/shared/game/medalTimes.ts: `npm run medals`.
// A medal lap is set from how fast the computer drivers lap alone on each
// track, in each league: BRONZE from a slow driver (skill 0.72), SILVER from
// MEDIUM (0.86) and GOLD a little faster than the flawless driver's best lap.
// Deterministic: the same simulation always writes the same table. Run it again after the physics or
// the tracks change.
import { writeFileSync } from 'node:fs';
import { DEFAULT_TUNING } from '../src/shared/config/tuning.ts';
import { leagueTuning, LEAGUES } from '../src/shared/game/leagues.ts';
import { getTrack } from '../src/shared/track/builder.ts';
import { TRACK_LIST } from '../src/shared/track/defs/index.ts';
import { stepWorld } from '../src/shared/sim/step.ts';
import { createWorld, RacePhase } from '../src/shared/sim/world.ts';
import type { Track } from '../src/shared/track/types.ts';
import type { CarTuning } from '../src/shared/config/tuning.ts';

/** GOLD is this much faster than the best lap of the HARD driver. */
const GOLD_FACTOR = 0.985;
/** BRONZE is this much slower than the best lap of the EASY driver. */
const BRONZE_FACTOR = 1.02;
/** Medals are at least this many ticks apart. */
const MIN_GAP = 6;

/** The best lap (ticks) of a lone computer driver of this skill over a few starts. */
function bestSoloLap(track: Track, tuning: CarTuning, skill: number): number {
  let best = Infinity;
  // Different countdowns shift the tick phase, so the line wander differs.
  for (const cd of [1, 37, 71, 113]) {
    const w = createWorld(track, 1, 3, { laps: 3, countdownTicks: cd });
    const c = w.cars[0];
    c.aiDriven = 1;
    c.aiSkill = skill;
    while (w.race.phase !== RacePhase.Finished && w.tick < 60 * 60 * 10) stepWorld(w, track, [], [tuning]);
    if (c.bestLapTicks > 0) best = Math.min(best, c.bestLapTicks);
  }
  if (!Number.isFinite(best)) throw new Error(`no lap for skill ${skill}`);
  return best;
}

// The medal drivers' skills are fixed, not the difficulties' (AI_SKILL), so
// tuning a difficulty never moves the medals: GOLD from the flawless driver
// (1.0), SILVER from MEDIUM's 0.86, BRONZE from 0.72 (EASY before it was made
// slower).
const [easy, medium, hard] = [0.72, 0.86, 1];
const rows: string[] = [];
for (const def of TRACK_LIST) {
  const track = getTrack(def);
  const cells: string[] = [];
  for (const league of LEAGUES) {
    const tuning = leagueTuning(DEFAULT_TUNING, league);
    const e = bestSoloLap(track, tuning, easy);
    const m = bestSoloLap(track, tuning, medium);
    const h = bestSoloLap(track, tuning, hard);
    const gold = Math.floor(h * GOLD_FACTOR);
    const silver = Math.max(gold + MIN_GAP, m);
    const bronze = Math.max(silver + MIN_GAP, Math.round(e * BRONZE_FACTOR));
    cells.push(`${league}: [${gold}, ${silver}, ${bronze}]`);
    console.log(def.name.padEnd(16), league.padEnd(9), `gold ${(gold / 60).toFixed(2)}  silver ${(silver / 60).toFixed(2)}  bronze ${(bronze / 60).toFixed(2)}`);
  }
  rows.push(`  ${def.id}: { ${cells.join(', ')} },`);
}

const out = `// Medal lap times in simulation ticks: [GOLD, SILVER, BRONZE] per track and league.
// Generated by \`npm run medals\` (scripts/medals.ts) from solo laps of the computer
// drivers. Do not edit by hand; run it again after the physics or the tracks change.

import type { League } from './leagues.ts';

export const MEDAL_TICKS: Record<string, Record<League, readonly [number, number, number]>> = {
${rows.join('\n')}
};
`;
writeFileSync(new URL('../src/shared/game/medalTimes.ts', import.meta.url), out);
console.log('wrote src/shared/game/medalTimes.ts');
